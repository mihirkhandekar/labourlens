"""Scripted MCP client demo: every step is a real call to a real server subprocess; the transcript is written from what happened.

Covers discovery, a valid call, rejected arguments (client and server side), a correctable 'too large', a timeout, an injected
instruction in a result, a hostile identity, a crashed server, a missing-secret check, one observed call of each added tool, the
loopback HTTP transport (authenticated call, 401 without a token, refused starts and URLs), and the direct-vs-MCP comparison.
"""

