# The committed transcript (docs/mcp-demo-transcript.md) is a recorded run that the report reads. By default a new run
# goes to this gitignored path, so following the README never dirties the checkout; pass --out to overwrite the record.
COMMITTED = paths.ROOT / "docs" / "mcp-demo-transcript.md"
OUT = paths.ROOT / "data" / "runs" / "mcp-demo-transcript.md"
ARGS = dict(source_id="retrenched_employees", period_from="2026-Q1", period_to="2026-Q2")


def _j(o, n=420) -> str:
    s = json.dumps(o, ensure_ascii=False, default=str)
    return s if len(s) <= n else s[:n] + " ..."


async def _attempt(label, coro, log):
    t0 = time.perf_counter()
    try:
        r = await coro
        log.append((label, "OK", r, time.perf_counter() - t0))
        return r
    except McpClientError as e:
        log.append((label, f"REJECTED/FAILED ({e.kind})", e.message, time.perf_counter() - t0))


async def demo() -> str:
    log: list[tuple] = []
    out = ["# MCP client demo transcript", "", "Generated by `uv run labourlens mcp-demo`. Every line below is the observed result of a real call to a real server subprocess "
           "(stdio transport; section 16 uses loopback HTTP). Nothing is mocked except that steps 7 to 12 deliberately talk to a hostile or faulty fixture server (`src/labourlens/mcp/evil.py`), "
           "registered on the allow-list for this demo only.", ""]

    async with McpStatsClient() as c:
        out += ["## 1. Discovery", ""]
        out += [f"- initialize: server `{c.transcript[0]['server']}` v{c.transcript[0]['version']}, protocol `{c.transcript[0]['protocol']}`"]
        tools = (await c.session.list_tools()).tools
        for t in tools:
            a = t.annotations
            out += [f"- tool `{t.name}`: read_only={a.read_only_hint}, destructive={a.destructive_hint}, idempotent={a.idempotent_hint}, open_world={a.open_world_hint}",
                    f"  - input schema: `{_j(t.input_schema, 900)}`"]
        out += [f"- resources: {await c.list_resources()}"]
        cat = await c.read_resource("labourlens://sources")
        out += [f"- `labourlens://sources`: {len(cat['datasets'])} datasets, {len(cat['documents'])} documents (metadata only; `text_served_by_this_server=false`), trust=`{cat['trust']}`", ""]

        out += ["## 2. Valid call", ""]
        r = await _attempt("get_statistic retrenched_employees 2026-Q1..Q2", c.get_statistic(**ARGS), log)
        out += [f"- `{_j(ARGS)}` -> {len(r.rows)} rows in {r.seconds * 1000:.0f} ms: " + "; ".join(f"{x['period']} {x['display']} ({x['release_stage']})" for x in r.rows), ""]

        out += ["## 3. Invalid arguments are rejected, twice", ""]
        for label, bad in [("unknown source_id (enum)", dict(ARGS, source_id="nope")), ("malformed period (pattern)", dict(ARGS, period_from="Q1 2026")),
                           ("period outside the supported range (server rule)", dict(ARGS, period_from="2023-Q1")),
                           ("84 rows requested without a dimension (too large)", dict(source_id="retrenched_by_industry", period_from="2026-Q1", period_to="2026-Q2"))]:
            await _attempt(label, c.get_statistic(**bad), log)
            out += [f"- {label}: **{log[-1][1]}**: {str(log[-1][2])[:200]}"]
        res = await c.session.call_tool("get_statistic", dict(ARGS, source_id="nope"))
        out += [f"- client-side check bypassed on purpose, server still refuses: is_error={res.is_error}: {res.content[0].text[:160]}", ""]

    async def hostile(mode, step, desc, call_t=1.5):
        name = register_test_server(f"evil-{mode}", mode)
        t0 = time.perf_counter()
        try:
            async with McpStatsClient(name, call_timeout_s=call_t, connect_timeout_s=20) as hc:
                r = await hc.get_statistic(**ARGS)
                rows = [x["dimension"] for x in r.rows if x["dimension"]]
                return [f"## {step}. {desc}", "", f"- result: {len(r.rows)} rows accepted, {r.quarantined} quarantined, ignored tools {r.ignored_tools}, injected text still present in accepted rows: {rows}", ""]
        except McpClientError as e:
            return [f"## {step}. {desc}", "", f"- failed closed: **{e.kind}**, {time.perf_counter() - t0:.1f} s in total including server start and shutdown: {e.message[:140]}", ""]

    for mode, desc in [("slow", "Slow server: the call times out (1.5 s limit)"), ("inject", "Result row carries an instruction: quarantined"),
                       ("subtle_inject", "Result row carries an instruction the heuristics do NOT catch: it passes the client (known limit; later layers handle it)"),
                       ("crash", "Server dies mid-call: unavailable, never reported as 'no data'"), ("wrong_version", "Server reports an unexpected version: refused"),
                       ("bad_name", "Server reports an unexpected identity: refused"), ("malformed", "Server breaks its own output schema: refused"),
                       ("oversized", "Server returns 400 KB: refused by the size cap"), ("extra_tool", "Server advertises an extra `run_shell` tool: ignored, never callable")]:
        out += await hostile(mode, {"slow": 4, "inject": 5, "subtle_inject": 6, "crash": 7, "wrong_version": 8, "bad_name": 9, "malformed": 10, "oversized": 11, "extra_tool": 12}[mode], desc)

    name = register_test_server("evil-env", "env_probe")
    async with McpStatsClient(name) as c:
        res = await c.session.call_tool("get_statistic", ARGS)
        out += ["## 13. The server process does not inherit secrets", "", f"- server saw `{res.structured_content['note']}` (the client passes a minimal environment; this process has OPENAI_API_KEY set)", ""]
    try:
        McpStatsClient("some-other-server")
    except McpClientError as e:
        out += ["## 14. Servers outside the allow-list are never started", "", f"- `some-other-server` -> **{e.kind}**: {e.message}", ""]

    out += await new_tools()
    out += await http_section()
    out += await comparison()
    return "\n".join(out) + "\n"


async def new_tools() -> list[str]:
    """One observed call of each added tool (stdio), plus one correctable refusal that shows the guard rails."""
    out = ["## 15. The added read-only tools: one observed call each", ""]
    async with McpStatsClient() as c:
        async def show(label, coro, fmt):
            try:
                r = await coro
                out.append(f"- **{label}** ({r.seconds * 1000:.0f} ms, {r.bytes} bytes, {r.quarantined} quarantined): {fmt(r.result)}")
                return r
            except McpClientError as e:
                out.append(f"- **{label}** refused ({e.kind}): {e.message[:300]}")

        await show("list_datasets(topic='retrench')", c.list_datasets("retrench"),
                   lambda r: f"{r.dataset_count} datasets: " + ", ".join(d.source_id for d in r.datasets[:6]) + (" ..." if r.dataset_count > 6 else ""))
        await show("describe_dataset('resident_unemployment_rate')", c.describe_dataset("resident_unemployment_rate"),
                   lambda r: f"{r.title} ({r.publisher}); series " + "; ".join(f"{i.indicator_id} [{i.unit}, {i.population}, {i.adjustment}]" for i in r.indicators)
                   + f"; {len(r.periods_in_scope)} periods {r.periods_in_scope[0]} to {r.periods_in_scope[-1]}; stages {r.release_stages}; licence {r.licence[:30]}...; {r.canonical_url}")
        await show("get_dimension_values('retrenched_by_occupation')", c.get_dimension_values("retrenched_by_occupation"), lambda r: f"{r.dimension_count} values: {r.values}")
        await show("latest_value('resident_unemployment_rate')", c.latest_value("resident_unemployment_rate"),
                   lambda r: "; ".join(f"{i.adjustment}: {i.display} in {i.period} ({i.release_stage})" for i in r.items))
        await show("compare_periods(retrenched_employees, 2026-Q1, 2026-Q2)", c.compare_periods("retrenched_employees", "2026-Q1", "2026-Q2"),
                   lambda r: f"{r.value_a:g} -> {r.value_b:g} {r.unit}; difference {r.difference.value} {r.difference.unit} [{r.difference.formula}]; relative change {r.relative_change.value} {r.relative_change.unit}")
        await show("compare_periods(resident_unemployment_rate, not_adjusted, 2024-Q1, 2026-Q2)",
                   c.compare_periods("resident_unemployment_rate", "2024-Q1", "2026-Q2", adjustment="not_adjusted"),
                   lambda r: f"{r.value_a:g}% -> {r.value_b:g}%; difference {r.difference.value} {r.difference.unit}; relative change {r.relative_change.value} {r.relative_change.unit}; {r.explanation}")
        await show("compare_periods(resident_unemployment_rate) without an adjustment", c.compare_periods("resident_unemployment_rate", "2025-Q1", "2026-Q1"), lambda r: "")
        await show("series_summary(retrenched_employees, 2024-Q1..2026-Q2)", c.series_summary("retrenched_employees", "2024-Q1", "2026-Q2"),
                   lambda r: f"first {r.first.value:g} ({r.first.period}), last {r.last.value:g} ({r.last.period}), min {r.minimum.value:g} ({r.minimum.period}), max {r.maximum.value:g} ({r.maximum.period}), direction {r.direction}")
        await show("get_revisions()", c.get_revisions(),
                   lambda r: f"{r.sources_checked} datasets checked, {r.sources_with_revisions} with changes. {r.message}")
        stat = await c.get_statistic(source_id="retrenched_employees", period_from="2026-Q2", period_to="2026-Q2")
        await show(f"get_provenance('{stat.rows[0]['observation_id']}')", c.get_provenance(stat.rows[0]["observation_id"]),
                   lambda r: f"{r.publisher}; {r.canonical_url}; retrieved {r.retrieved_utc}; snapshot {r.snapshot_id}; sha256 {r.sha256[:16]}...; {r.source_locator}; transformations: {r.transformations}")
        await show("get_provenance('mom-2026-q1-final:p002:b003:d2827a5b') (a report passage id)", c.get_provenance("mom-2026-q1-final:p002:b003:d2827a5b"), lambda r: "")
        try:
            await c.call("run_shell", command="id")
        except McpClientError as e:
            out.append(f"- **call('run_shell')** refused ({e.kind}): {e.message}")
    out.append("")
    return out


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


async def http_section() -> list[str]:
    """Start the real server on a free loopback port with a random token, then try it with and without credentials."""
    out = ["## 16. Loopback HTTP transport with a bearer token", ""]
    token, port = secrets.token_urlsafe(32), _free_port()
    url = f"http://127.0.0.1:{port}/mcp"
    base_env = {k: v for k, v in os.environ.items() if k != TOKEN_ENV}
    out.append(f"- start: `python -m labourlens.mcp.server --transport http --host 127.0.0.1 --port {port}` with `{TOKEN_ENV}` set to a random {len(token)}-character token (not shown)")
    proc = subprocess.Popen([sys.executable, "-m", "labourlens.mcp.server", "--transport", "http", "--host", "127.0.0.1", "--port", str(port)],
                            env={**base_env, TOKEN_ENV: token}, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    old = os.environ.get(TOKEN_ENV)
    try:
        for _ in range(200):
            if proc.poll() is not None:
                return out + [f"- server exited early with code {proc.returncode}", ""]
            try:
                socket.create_connection(("127.0.0.1", port), timeout=0.5).close()
                break
            except OSError:
                await asyncio.sleep(0.3)
        os.environ[TOKEN_ENV] = token
        name = register_http_server("http-demo", url)
        async with McpStatsClient(name) as c:
            t = c.transcript[0]
            r = await c.get_statistic(**ARGS)
            cmp = await c.compare_periods("retrenched_employees", "2026-Q1", "2026-Q2")
            out += [f"- authenticated client: initialize over `{t['transport']}` -> server `{t['server']}` v{t['version']}, {len(c.schemas)} tools; get_statistic -> {len(r.rows)} rows "
                    + "; ".join(f"{x['period']} {x['display']}" for x in r.rows) + f"; compare_periods difference {cmp.result.difference.value} {cmp.result.difference.unit}"]
        hdr = {"content-type": "application/json", "accept": "application/json, text/event-stream"}
        body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-03-26", "capabilities": {}, "clientInfo": {"name": "probe", "version": "0"}}})

        def probe(label, headers):
            resp = httpx.post(url, headers={**hdr, **headers}, content=body, timeout=10)
            out.append(f"- {label}: **HTTP {resp.status_code}**, body {len(resp.content)} bytes, `WWW-Authenticate: {resp.headers.get('www-authenticate')}`")

        probe("request with no Authorization header (this is also the health probe: 401 means up and enforcing)", {})
        probe("request with a wrong token", {"authorization": "Bearer " + secrets.token_urlsafe(32)})
        probe("valid token but Host header `evil.example.com` (DNS-rebinding check)", {"authorization": f"Bearer {token}", "host": "evil.example.com"})
        probe("valid token but browser Origin `http://evil.example.com`", {"authorization": f"Bearer {token}", "origin": "http://evil.example.com"})
        os.environ[TOKEN_ENV] = secrets.token_urlsafe(32)
        try:
            async with McpStatsClient(name):
                out.append("- wrong token through the client: connected (unexpected)")
        except McpClientError as e:
            out.append(f"- the client with a wrong token fails closed: **{e.kind}** ({e.message})")
    finally:
        if old is None:
            os.environ.pop(TOKEN_ENV, None)
        else:
            os.environ[TOKEN_ENV] = old
        proc.terminate()
        try:
            err = proc.communicate(timeout=15)[1]
        except subprocess.TimeoutExpired:
            proc.kill()
            err = proc.communicate()[1]
    out.append(f"- the token does not appear in the server's stderr ({len(err.splitlines())} lines): **{token not in err}**")
    refuse = subprocess.run([sys.executable, "-m", "labourlens.mcp.server", "--transport", "http", "--host", "0.0.0.0", "--port", str(_free_port())],
                            env={**base_env, TOKEN_ENV: secrets.token_urlsafe(32)}, capture_output=True, text=True, timeout=60)
    out.append(f"- start with `--host 0.0.0.0`: exit code {refuse.returncode}: `{refuse.stderr.strip().splitlines()[-1][:200]}`")
    refuse = subprocess.run([sys.executable, "-m", "labourlens.mcp.server", "--transport", "http", "--port", str(_free_port())],
                            env={**base_env, TOKEN_ENV: "short"}, capture_output=True, text=True, timeout=60)
    out.append(f"- start with a 5-character token: exit code {refuse.returncode}: `{refuse.stderr.strip().splitlines()[-1][:200]}`")
    os.environ[TOKEN_ENV] = secrets.token_urlsafe(32)
    try:
        McpStatsClient(register_http_server("http-remote", "http://192.0.2.1:8765/mcp"))
    except McpClientError as e:
        out.append(f"- client configured with a non-loopback URL: **{e.kind}**: {e.message}")
    finally:
        os.environ.pop(TOKEN_ENV, None) if old is None else os.environ.__setitem__(TOKEN_ENV, old)
    out.append("")
    return out


async def comparison() -> list[str]:
    """Direct function call versus MCP: same output? what does the protocol cost?"""
    direct = StatsData()
    ids = sorted(direct.obs["source_id"].unique())
    same = diff = skipped = 0
    d_lat, m_lat = [], []
    t0 = time.perf_counter()
    c = McpStatsClient()
    await c.__aenter__()
    cold = time.perf_counter() - t0
    try:
        for sid in ids:
            a = dict(source_id=sid, period_from="2024-Q1", period_to="2026-Q2")
            t1 = time.perf_counter()
            rows, err = direct.query(**a)
            d_lat.append(time.perf_counter() - t1)
            try:
                t2 = time.perf_counter()
                reply = await c.get_statistic(**a)
                m_lat.append(time.perf_counter() - t2)
            except McpClientError as e:
                skipped += 1
                assert err is not None, f"{sid}: MCP failed ({e.kind}) but direct succeeded"
                continue
            if err is not None:
                diff += 1
            elif reply.rows == rows:
                same += 1
            else:
                diff += 1
    finally:
        await c.__aexit__(None, None, None)
    ms = lambda xs: f"{statistics.median(xs) * 1000:.1f} ms"  # noqa: E731
    return ["## 17. Direct call versus MCP", "",
            f"Query: every one of the {len(ids)} in-scope datasets over 2024-Q1 to 2026-Q2.", "",
            "| | direct function call | MCP over stdio (warm session) |", "|---|---|---|",
            f"| median latency per call | {ms(d_lat)} | {ms(m_lat)} |", f"| p95 latency per call | {sorted(d_lat)[int(len(d_lat) * .95) - 1] * 1000:.1f} ms | {sorted(m_lat)[int(len(m_lat) * .95) - 1] * 1000:.1f} ms |",
            f"| one-off connection cost (spawn + initialize + discovery) | none | {cold:.2f} s |",
            f"| identical rows | {same} of {len(ids)} datasets | |", f"| datasets where both refused the same over-large query | {skipped} | |",
            f"| datasets where outputs differed | {diff} | |", ""]


def run(out: Path | None = None) -> None:
    target = out or OUT
    text = asyncio.run(demo())
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    print(text)
    print(f"\ntranscript written to {target}")
