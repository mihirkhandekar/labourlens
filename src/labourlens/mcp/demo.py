"""Scripted MCP client demo: every step is a real call to a real server subprocess; the transcript is written from what happened.

Covers discovery, a valid call, rejected arguments (client and server side), a correctable 'too large', a timeout, an injected
instruction in a result, a hostile identity, a crashed server, a missing-secret check, and the direct-vs-MCP comparison.
"""

from __future__ import annotations

import asyncio
import json
import statistics
import time

from labourlens import paths
from labourlens.agent.tools import StatsData
from labourlens.mcp.client import McpClientError, McpStatsClient, register_test_server

OUT = paths.ROOT / "docs" / "mcp-demo-transcript.md"
ARGS = dict(source_id="retrenched_employees", period_from="2026-Q1", period_to="2026-Q2")


def _j(o, n=420) -> str:
    s = json.dumps(o, ensure_ascii=False, default=str)
    return s if len(s) <= n else s[:n] + " ..."


async def _attempt(label, coro, log):
    t0 = time.perf_counter()
    try:
        r = await coro
        log.append((label, "OK", r, time.perf_counter() - t0))
        return r
    except McpClientError as e:
        log.append((label, f"REJECTED/FAILED ({e.kind})", e.message, time.perf_counter() - t0))


async def demo() -> str:
    log: list[tuple] = []
    out = ["# MCP client demo transcript", "", "Generated by `uv run labourlens mcp-demo`. Every line below is the observed result of a real call to a real server subprocess "
           "(stdio transport). Nothing is mocked except that steps 7 to 12 deliberately talk to a hostile or faulty fixture server (`src/labourlens/mcp/evil.py`), "
           "registered on the allow-list for this demo only.", ""]

    async with McpStatsClient() as c:
        out += ["## 1. Discovery", ""]
        out += [f"- initialize: server `{c.transcript[0]['server']}` v{c.transcript[0]['version']}, protocol `{c.transcript[0]['protocol']}`"]
        tools = (await c.session.list_tools()).tools
        for t in tools:
            a = t.annotations
            out += [f"- tool `{t.name}`: read_only={a.read_only_hint}, destructive={a.destructive_hint}, idempotent={a.idempotent_hint}, open_world={a.open_world_hint}",
                    f"  - input schema: `{_j(t.input_schema, 900)}`"]
        out += [f"- resources: {await c.list_resources()}"]
        cat = await c.read_resource("labourlens://sources")
        out += [f"- `labourlens://sources`: {len(cat['datasets'])} datasets, {len(cat['documents'])} documents (metadata only; `text_served_by_this_server=false`), trust=`{cat['trust']}`", ""]

        out += ["## 2. Valid call", ""]
        r = await _attempt("get_statistic retrenched_employees 2026-Q1..Q2", c.get_statistic(**ARGS), log)
        out += [f"- `{_j(ARGS)}` -> {len(r.rows)} rows in {r.seconds * 1000:.0f} ms: " + "; ".join(f"{x['period']} {x['display']} ({x['release_stage']})" for x in r.rows), ""]

        out += ["## 3. Invalid arguments are rejected, twice", ""]
        for label, bad in [("unknown source_id (enum)", dict(ARGS, source_id="nope")), ("malformed period (pattern)", dict(ARGS, period_from="Q1 2026")),
                           ("period outside the supported range (server rule)", dict(ARGS, period_from="2023-Q1")),
                           ("84 rows requested without a dimension (too large)", dict(source_id="retrenched_by_industry", period_from="2026-Q1", period_to="2026-Q2"))]:
            await _attempt(label, c.get_statistic(**bad), log)
            out += [f"- {label}: **{log[-1][1]}**: {str(log[-1][2])[:200]}"]
        res = await c.session.call_tool("get_statistic", dict(ARGS, source_id="nope"))
        out += [f"- client-side check bypassed on purpose, server still refuses: is_error={res.is_error}: {res.content[0].text[:160]}", ""]

    async def hostile(mode, step, desc, call_t=1.5):
        name = register_test_server(f"evil-{mode}", mode)
        t0 = time.perf_counter()
        try:
            async with McpStatsClient(name, call_timeout_s=call_t, connect_timeout_s=20) as hc:
                r = await hc.get_statistic(**ARGS)
                rows = [x["dimension"] for x in r.rows if x["dimension"]]
                return [f"## {step}. {desc}", "", f"- result: {len(r.rows)} rows accepted, {r.quarantined} quarantined, ignored tools {r.ignored_tools}, injected text still present in accepted rows: {rows}", ""]
        except McpClientError as e:
            return [f"## {step}. {desc}", "", f"- failed closed: **{e.kind}**, {time.perf_counter() - t0:.1f} s in total including server start and shutdown: {e.message[:140]}", ""]

    for mode, desc in [("slow", "Slow server: the call times out (1.5 s limit)"), ("inject", "Result row carries an instruction: quarantined"),
                       ("subtle_inject", "Result row carries an instruction the heuristics do NOT catch: it passes the client (known limit; later layers handle it)"),
                       ("crash", "Server dies mid-call: unavailable, never reported as 'no data'"), ("wrong_version", "Server reports an unexpected version: refused"),
                       ("bad_name", "Server reports an unexpected identity: refused"), ("malformed", "Server breaks its own output schema: refused"),
                       ("oversized", "Server returns 400 KB: refused by the size cap"), ("extra_tool", "Server advertises an extra `run_shell` tool: ignored, never callable")]:
        out += await hostile(mode, {"slow": 4, "inject": 5, "subtle_inject": 6, "crash": 7, "wrong_version": 8, "bad_name": 9, "malformed": 10, "oversized": 11, "extra_tool": 12}[mode], desc)

    name = register_test_server("evil-env", "env_probe")
    async with McpStatsClient(name) as c:
        res = await c.session.call_tool("get_statistic", ARGS)
        out += ["## 13. The server process does not inherit secrets", "", f"- server saw `{res.structured_content['note']}` (the client passes a minimal environment; this process has OPENAI_API_KEY set)", ""]
    try:
        McpStatsClient("some-other-server")
    except McpClientError as e:
        out += ["## 14. Servers outside the allow-list are never started", "", f"- `some-other-server` -> **{e.kind}**: {e.message}", ""]

    out += await comparison()
    return "\n".join(out) + "\n"


async def comparison() -> list[str]:
    """Direct function call versus MCP: same output? what does the protocol cost?"""
    direct = StatsData()
    ids = sorted(direct.obs["source_id"].unique())
    same = diff = skipped = 0
    d_lat, m_lat = [], []
    t0 = time.perf_counter()
    c = McpStatsClient()
    await c.__aenter__()
    cold = time.perf_counter() - t0
    try:
        for sid in ids:
            a = dict(source_id=sid, period_from="2024-Q1", period_to="2026-Q2")
            t1 = time.perf_counter()
            rows, err = direct.query(**a)
            d_lat.append(time.perf_counter() - t1)
            try:
                t2 = time.perf_counter()
                reply = await c.get_statistic(**a)
                m_lat.append(time.perf_counter() - t2)
            except McpClientError as e:
                skipped += 1
                assert err is not None, f"{sid}: MCP failed ({e.kind}) but direct succeeded"
                continue
            if err is not None:
                diff += 1
            elif reply.rows == rows:
                same += 1
            else:
                diff += 1
    finally:
        await c.__aexit__(None, None, None)
    ms = lambda xs: f"{statistics.median(xs) * 1000:.1f} ms"  # noqa: E731
    return ["## 15. Direct call versus MCP", "",
            f"Query: every one of the {len(ids)} in-scope datasets over 2024-Q1 to 2026-Q2.", "",
            "| | direct function call | MCP over stdio (warm session) |", "|---|---|---|",
            f"| median latency per call | {ms(d_lat)} | {ms(m_lat)} |", f"| p95 latency per call | {sorted(d_lat)[int(len(d_lat) * .95) - 1] * 1000:.1f} ms | {sorted(m_lat)[int(len(m_lat) * .95) - 1] * 1000:.1f} ms |",
            f"| one-off connection cost (spawn + initialize + discovery) | none | {cold:.2f} s |",
            f"| identical rows | {same} of {len(ids)} datasets | |", f"| datasets where both refused the same over-large query | {skipped} | |",
            f"| datasets where outputs differed | {diff} | |", ""]


def run() -> None:
    text = asyncio.run(demo())
    OUT.write_text(text)
    print(text)
